import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { galleryEntries } from '../src/data/gallery-entries.js'

const root = fileURLToPath(new URL('../', import.meta.url))
const sourceDirectory = path.join(root, 'src/assets/gallery')
const thumbnailDirectory = path.join(root, 'src/assets/gallery-thumbnails')
const modulePath = path.join(root, 'src/data/generated/gallery-assets.js')
const files = [...new Set(galleryEntries.flatMap(({ items }) => items.map(({ file }) => file)))]
const imports = []
const records = []
let originalBytes = 0
let thumbnailBytes = 0

for (const [index, file] of files.entries()) {
  // Append the extension so JPG/PNG files with the same name cannot collide.
  if (file.includes('\\') || path.isAbsolute(file) ||
      file.split('/').some((part) => !part || part === '..' || part === '.')) {
    throw new Error(`Invalid gallery path: ${file}`)
  }

  const source = await readFile(path.join(sourceDirectory, file))
  const metadata = await sharp(source).metadata()
  const size = Math.min(800, metadata.width, metadata.height)
  const thumbnailFile = `${file}.webp`
  const target = path.join(thumbnailDirectory, thumbnailFile)
  const { data, info } = await sharp(source)
    .rotate()
    .resize(size, size, { fit: 'cover', position: 'centre', withoutEnlargement: true })
    .webp({ quality: 82, effort: 4 })
    .toBuffer({ resolveWithObject: true })

  await mkdir(path.dirname(target), { recursive: true })
  await writeFile(target, data)
  originalBytes += source.length
  thumbnailBytes += data.length

  imports.push(`import original${index} from ${JSON.stringify(`../../assets/gallery/${file}`)}`)
  imports.push(`import thumbnail${index} from ${JSON.stringify(`../../assets/gallery-thumbnails/${thumbnailFile}`)}`)
  records.push(`  ${JSON.stringify(file)}: { image: original${index}, thumbnail: thumbnail${index}, thumbnailWidth: ${info.width}, thumbnailHeight: ${info.height} },`)
}

await mkdir(path.dirname(modulePath), { recursive: true })
await writeFile(modulePath, [
  '// Generated by npm run gallery:thumbnails. Edit gallery-entries.js instead.',
  ...imports,
  '',
  'export const galleryAssets = {',
  ...records,
  '}',
  '',
].join('\n'))

const mb = (bytes) => (bytes / 1024 / 1024).toFixed(2)
const reduction = originalBytes ? ((1 - thumbnailBytes / originalBytes) * 100).toFixed(1) : '0.0'
console.log(`Generated ${files.length} gallery thumbnails: ${mb(originalBytes)} MiB → ${mb(thumbnailBytes)} MiB (${reduction}% smaller). Originals unchanged.`)
